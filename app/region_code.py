def get_region_from_district(district_code: str) -> str:
    """
    district 코드에서 region(시/도) 코드를 추출합니다.
    DISTRICT_TO_REGION 딕셔너리를 사용하여 매핑합니다.
    
    Args:
        district_code: district 코드 (문자열 또는 숫자)
    
    Returns:
        region 코드 (문자열) 또는 None
    """
    if not district_code:
        return None
    # district_code를 문자열로 변환하여 딕셔너리에서 조회
    district_str = str(district_code)
    return DISTRICT_TO_REGION.get(district_str)

